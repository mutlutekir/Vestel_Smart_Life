def humanize(role: str) -> str:
    import re
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", role.replace(".", " "))


def role_name(role: str) -> str:
    return ROLE_NAMES.get(role) or humanize(role)


def _int(value: Any) -> int | None:
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _field(raw: int, pos: int | None, length: int | None) -> int:
    if pos is None:
        return raw
    return (raw >> pos) & ((1 << (length or 1)) - 1)


def decode(family: str, registers: dict[str, Any]) -> dict[str, Any]:
    """Decode the registers of one appliance of ``family``.

    Returns ``values`` (role -> text or number), ``flags`` (role -> bool), the active error
    names and whether anything is reported as wrong (None when that cannot be told).
    """
    spec = TABLE[family]
    values: dict[str, Any] = {}
    flags: dict[str, bool] = {}
    for entry in spec["registers"]:
        raw = _int(registers.get(entry["reg"]))
        if raw is None:
            continue
        field = _field(raw, entry["pos"], entry["len"])
        kind = entry["kind"]
        if kind == "bool":
            flags[entry["role"]] = bool(field)
        elif kind == "enum":
            values[entry["role"]] = entry["values"].get(field, str(field))
        else:
            if entry.get("unit") in ("celsius", "celcius") and entry["pos"] is None and field > 32767:
                field -= 65536  # signed 16-bit; the encoding of sensor temperatures is not confirmed
            values[entry["role"]] = field
    errors: list[str] = []
    problem: bool | None = None
    for reg, bits in spec["error_bits"].items():
        raw = _int(registers.get(reg))
        if raw is None:
            continue
        problem = bool(problem)
        for pos, name in bits:
            if (raw >> pos) & 1:
                errors.append(name)
                problem = True
    for reg, codes in spec["error_codes"].items():
        raw = _int(registers.get(reg))
        if raw is None or reg in spec["error_bits"]:
            continue
        name = codes.get(raw, str(raw))
        no_error = next((v for v, label in codes.items() if label == "No Error"), None)
        values["Error"] = name
        if no_error is not None:
            problem = raw != no_error
            if problem:
                errors.append(name)
    return {"values": values, "flags": flags, "errors": errors, "problem": problem}
